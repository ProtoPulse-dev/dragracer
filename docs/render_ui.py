def text8(disp, s, x, y, color, bg=None):
    for i, ch in enumerate(s):
        cx = x + i * 8
        if cx < disp.w and y < disp.h:
            if bg is not None:
                disp.fill_rect(cx, y, 8, 8, bg)
            code = ord(ch)
            if code < 0x20 or code > 0x7E:
                code = 0x20
            off = (code - 0x20) * 8
            glyph = FONT8[off:off + 8]
            for col in range(8):
                bits = glyph[col]
                for row in range(8):
                    if bits & 1:
                        disp.pixel(cx + col, y + row, color)
                    bits >>= 1

# ---- draw helpers matching drag_race.py -----------------------------------
DARK_GRAY = 0x4208

def draw_status_dot(disp, x, y, color):
    disp.fill_rect(x, y, 4, 8, color)

def draw_top_rule(disp):
    disp.hline(0, 12, W, GRAY)

def draw_progress_bar(disp, x, y, w, h, pct, fill_color):
    fill_w = int(w * max(0.0, min(1.0, pct)))
    if fill_w > 0:
        disp.fill_rect(x, y, fill_w, h, fill_color)
    rem_x = x + fill_w
    rem_w = w - fill_w
    if rem_w > 0:
        disp.hline(rem_x, y, rem_w, DARK_GRAY)
        disp.hline(rem_x, y + h - 1, rem_w, DARK_GRAY)
        disp.vline(rem_x, y, h, DARK_GRAY)
        disp.vline(rem_x + rem_w - 1, y, h, DARK_GRAY)

# ---- render screens --------------------------------------------------------
def render_drive(disp, speed=0.0, timer=0.0, satellites=8, state="WAI"):
    disp.fill(BLACK)
    if state == "WAI":
        state_lbl, dot_color = "READY", GREEN
    elif state == "RUN":
        state_lbl, dot_color = "RUN", RED
    else:
        state_lbl, dot_color = "COOL", BLUE
    draw_status_dot(disp, 0, 0, dot_color)
    text8(disp, state_lbl, 8, 0, dot_color)
    text8(disp, "S%d" % min(satellites, 99), 142, 0, GRAY)
    disp.hline(0, 9, W, DARK_GRAY)
    if state == "RUN":
        digits38x56.draw_number_trimmed(disp, "%5.2f" % timer, 0, 10, RED)
        text8(disp, "s", 134, 54, GRAY)
        text8(disp, "%5.1f kmh" % speed, 78, 72, WHITE)
        pct = (speed - 60) / 60
        draw_progress_bar(disp, 0, 65, W, 4, pct, RED)
    else:
        digits38x56.draw_number_trimmed(disp, "%5.1f" % speed, 0, 10, WHITE)
        text8(disp, "kmh", 130, 50, GRAY)
        text8(disp, "T" + "%5.1f" % timer, 0, 70, DARK_GRAY)

def render_info(disp, speed=0.0, best_time=7.23, recent_runs=None, satellites=12):
    if recent_runs is None:
        recent_runs = [8.45, 7.89, 9.12]
    disp.fill(BLACK)
    text8(disp, "INFO", 0, 0, WHITE)
    text8(disp, "SAT%d" % min(satellites, 99), 60, 0, GRAY)
    text8(disp, "BEST", 120, 0, GRAY)
    draw_top_rule(disp)
    text8(disp, "BEST", 4, 16, GRAY)
    if best_time > 0:
        digits16x24.draw_number_right(disp, "%5.2f" % best_time, 78, 24, GREEN)
        text8(disp, "s", 82, 50, GRAY)
    else:
        text8(disp, "--.--", 4, 32, GRAY)
    disp.vline(80, 12, 68, DARK_GRAY)
    text8(disp, "LAST", 84, 16, GRAY)
    if not recent_runs:
        text8(disp, "no runs", 84, 32, GRAY)
    else:
        y = 30
        for i, run in enumerate(recent_runs[:3]):
            text8(disp, "%d." % (i + 1), 84, y, GRAY)
            text8(disp, "%5.2f s" % run, 100, y, WHITE)
            y += 14

# ---- PNG export -------------------------------------------------------------
def fb_to_png(disp, path):
    buf, w, h = disp.buf, disp.w, disp.h
    rgb = bytearray(w * h * 3)
    for y in range(h):
        for x in range(w):
            i = (y * w + x) * 2
            c = (buf[i] << 8) | buf[i + 1]
            r = ((c >> 11) & 0x1F) << 3
            g = ((c >> 5) & 0x3F) << 2
            b = (c & 0x1F) << 3
            j = (y * w + x) * 3
            rgb[j] = r
            rgb[j + 1] = g
            rgb[j + 2] = b

    def png_chunk(ctype, data):
        chunk = ctype + data
        crc = zlib.crc32(chunk) & 0xffffffff
        return struct.pack('>I', len(data)) + chunk + struct.pack('>I', crc)

    raw = bytearray()
    for y in range(h):
        raw.append(0)
        raw.extend(rgb[y * w * 3:(y + 1) * w * 3])

    out = bytearray(b'\x89PNG\r\n\x1a\n')
    out.extend(png_chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)))
    out.extend(png_chunk(b'IDAT', zlib.compress(bytes(raw), 9)))
    out.extend(png_chunk(b'IEND', b''))

    with open(path, 'wb') as f:
        f.write(out)
    print('wrote', path)

