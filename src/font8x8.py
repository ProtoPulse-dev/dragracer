def glyph(ch):
    """Return an 8-byte memoryview of the glyph for ASCII char `ch`."""
    code = ord(ch) if isinstance(ch, str) else ch
    if code < 0x20 or code > 0x7E:
        code = 0x20
    off = (code - 0x20) * 8
    return memoryview(font8x8_basic)[off:off + 8]


def draw_char(fb, ch, x, y, color):
    """Draw an 8x8 glyph to a framebuf.FrameBuffer in MONO_HLSB mode."""
    g = glyph(ch)
    for col in range(8):
        bits = g[col]
        for row in range(8):
            if bits & 1:
                fb.pixel(x + col, y + row, color)
            bits >>= 1
