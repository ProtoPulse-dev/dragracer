# Blit a digit (0-9) into a framebuf.FrameBuffer at (x,y) in RGB565 mode.
def draw_digit(fb, d, x, y, color):
    glyph = DIGITS[d]
    w, h = fb.width, fb.height
    for row in range(40):
        row_bits = (glyph[row*3] << 16) | (glyph[row*3 + 1] << 8) | glyph[row*3 + 2]
        for col in range(24):
            if row_bits & (1 << (23 - col)):
                px = x + col
                py = y + row
                if 0 <= px < w and 0 <= py < h:
                    fb.pixel(px, py, color)

def _text_width(s):
    total_w = 0
    for ch in s:
        if ch == '.':
            total_w += 6
        elif ch == ' ':
            total_w += 24
        elif ch.isdigit():
            total_w += 24
    return total_w

def draw_number(fb, s, x, y, color):
    x_pos = x
    for ch in s:
        if ch == '.':
            fb.fill_rect(x_pos - 2, y + 32, 4, 4, color)
            x_pos += 6
        elif ch == ' ':
            x_pos += 24
        elif ch.isdigit():
            draw_digit(fb, int(ch), x_pos, y, color)
            x_pos += 24

def draw_number_right(fb, s, x_end, y, color):
    draw_number(fb, s, x_end - _text_width(s), y, color)

def draw_number_trimmed(fb, s, x, y, color):
    draw_number(fb, s.lstrip(), x, y, color)
