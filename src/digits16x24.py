# Blit a digit (0-9) into a framebuf.FrameBuffer at (x,y) in RGB565 mode.
def draw_digit(fb, d, x, y, color):
    glyph = DIGITS[d]
    for row in range(24):
        row_bits = (glyph[row*2] << 8) | glyph[row*2 + 1]
        for col in range(16):
            if row_bits & (1 << (15 - col)):
                fb.pixel(x + col, y + row, color)

# Draw a big number string using the 16x24 digits plus decimal point.
# Supports fixed-width layout with decimal point.
def draw_number(fb, s, x, y, color):
    x_pos = x
    for ch in s:
        if ch == '.':
            fb.fill_rect(x_pos - 2, y + 18, 3, 3, color)
            x_pos += 4
        elif ch == ' ':
            x_pos += 16
        elif ch.isdigit():
            draw_digit(fb, int(ch), x_pos, y, color)
            x_pos += 16

# Right-align a number string ending at x_end.
def draw_number_right(fb, s, x_end, y, color):
    total_w = 0
    for ch in s:
        if ch == '.':
            total_w += 4
        elif ch == ' ':
            total_w += 16
        elif ch.isdigit():
            total_w += 16
    draw_number(fb, s, x_end - total_w, y, color)
